    public static void setBoard() {
        for (int i = 0; i < 5; i++) {
            for (int j = 0; j < 5; j++) {
                board[i][j] = 0;
            }
        }
    }

    public static void printBoard() {
        System.out.println("  1 2 3 4 5");
        for (int i = 0; i < 5; i++) {
            System.out.print(i + 1);
            for (int j = 0; j < 5; j++) {
                switch (board[i][j]) {
                    case 0: System.out.print(" -"); break;
                    case 1: System.out.print(" X"); break;
                    case 2: System.out.print(" O"); break;
                }
            }
            System.out.println();
        }
        System.out.println();
    }

    public static boolean setMove(int move, int player) {
        int i = (move / 10) - 1;
        int j = (move % 10) - 1;
        if (i < 0 || i > 4 || j < 0 || j > 4) return false;
        if (board[i][j] != 0) return false;
        board[i][j] = player;
        return true;
    }

    public static boolean winCheck(int player) {
        for (int[][] line : win) {
            if (board[line[0][0]][line[0][1]] == player &&
                board[line[1][0]][line[1][1]] == player &&
                board[line[2][0]][line[2][1]] == player &&
                board[line[3][0]][line[3][1]] == player) {
                return true;
            }
        }
        return false;
    }

    public static boolean loseCheck(int player) {
        for (int[][] line : lose) {
            if (board[line[0][0]][line[0][1]] == player &&
                board[line[1][0]][line[1][1]] == player &&
                board[line[2][0]][line[2][1]] == player) {
                return true;
            }
        }
        return false;
    }
